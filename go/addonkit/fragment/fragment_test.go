package fragment

import (
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// fixtureVersion is the kit version both renderers are given for the shared fixtures.
const fixtureVersion = "0.0.0-fixture"

// The shared fixtures: testdata/<name>.json holds a kit.json (what the CLI's vendor renders) and the
// Fragment that says the same, <name>.conf the one text both must write. test/cli/fragment.test.mjs
// checks the CLI against the same files.
func TestRenderFixtures(t *testing.T) {
	files, err := filepath.Glob("testdata/*.json")
	if err != nil || len(files) == 0 {
		t.Fatalf("no fixtures: %v", err)
	}
	for _, file := range files {
		name := strings.TrimSuffix(filepath.Base(file), ".json")
		t.Run(name, func(t *testing.T) {
			raw, err := os.ReadFile(file)
			if err != nil {
				t.Fatal(err)
			}
			var fx struct {
				Fragment Fragment `json:"fragment"`
			}
			if err := json.Unmarshal(raw, &fx); err != nil {
				t.Fatal(err)
			}
			want, err := os.ReadFile(strings.TrimSuffix(file, ".json") + ".conf")
			if err != nil {
				t.Fatal(err)
			}
			fx.Fragment.KitVersion = fixtureVersion
			got, err := Render(fx.Fragment)
			if err != nil {
				t.Fatal(err)
			}
			if got != string(want) {
				t.Errorf("got\n%s\nwant\n%s", got, want)
			}
		})
	}
}

func TestRender(t *testing.T) {
	plain, err := Render(Fragment{ID: "x", Port: 1234})
	if err != nil || !strings.Contains(plain, `$HTTP["url"] =~ "^/addons/x/" {`) || strings.Contains(plain, "upgrade") ||
		!strings.HasPrefix(plain, "# etc/lighttpd.conf - generated by ccu-addon-kit go (MIT); do not edit\n") {
		t.Fatalf("plain: %v\n%s", err, plain)
	}
	sock, err := Render(Fragment{ID: "x", Socket: "/usr/local/addons/x/var/x.sock"})
	if err != nil || !strings.Contains(sock, `proxy.server = ("/addons/x/" => (("socket" => "/usr/local/addons/x/var/x.sock")))`) {
		t.Fatalf("socket: %v\n%s", err, sock)
	}
	// the frame in /addons/<www>/: a www of its own leaves /addons/<id>/ to the proxy; the id's own
	// www keeps the directory, kit/ and frame/ to lighttpd
	for _, ok := range []Fragment{
		{ID: "x", WWW: "x-config", Port: 1},
		{ID: "x", WWW: "x", Path: "/addons/x/app/", Port: 1},
		{ID: "x", Path: "/addons/x/", Port: 1},
	} {
		if _, err := Render(ok); err != nil {
			t.Errorf("refused %+v: %v", ok, err)
		}
	}
	for _, bad := range []Fragment{
		{ID: "Bad", Port: 1},
		{ID: "x", Port: 0},
		{ID: "x", Port: 70000},
		{ID: "x", Socket: "/tmp/x.sock"},
		{ID: "x", Socket: "/usr/local/addons/x/../y.sock"},
		{ID: "x", Port: 1, ErrorfilePrefix: "/usr/local/addons/y/e-"},
		{ID: "x", Port: 1, ErrorfilePrefix: "/usr/local/addons/x/\"e-"},
		{ID: "x", Port: 1, Path: "/addons/y/"},
		{ID: "x", Port: 1, Path: "/addons/x"},
		{ID: "x", Port: 1, Path: "/addons/x/a b/"},
		{ID: "x", Port: 1, Path: "/addons/x/../y/"},
		{ID: "x", Port: 1, WWW: "x"},
		{ID: "x", Port: 1, WWW: "x", Path: "/addons/x/kit/"},
		{ID: "x", Port: 1, WWW: "x", Path: "/addons/x/frame/assets/"},
		{ID: "x", Port: 1, WWW: "../etc"},
		{ID: "x", Port: 1, KitVersion: "1\n$HTTP"},
	} {
		if _, err := Render(bad); err == nil {
			t.Errorf("accepted %+v", bad)
		}
	}
}
